        <article>
            <h1 class="text-2xl font-bold text-slate-900 sm:text-3xl">
                Política de tratamiento de datos personales
            </h1>
            <p class="text-sm text-slate-500">
                Elaborada conforme a la Ley N.º 29733, Ley de Protección de Datos Personales, del Perú.
            </p>

            <p class="mt-6 text-slate-700">
                Esta política explica, en lenguaje sencillo, qué información recogemos cuando te
                registras en Alumni Connect EFPISC, para qué la usamos, cuánto tiempo la guardamos,
                con quién la compartimos y qué puedes hacer si quieres revisarla, corregirla o pedir
                que la eliminemos.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">1. ¿Quién es el responsable de tus datos?</h2>
            <p class="text-slate-700">
                La responsable del tratamiento de tus datos personales es la
                <strong>Escuela de Formación Profesional de Ingeniería de Sistemas y Computación</strong>,
                de la <strong>Universidad Nacional Daniel Alcides Carrión (UNDAC)</strong>. Es la Escuela
                quien decide para qué se usa tu información dentro de esta plataforma y quien responde
                ante ti por su cuidado.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">2. ¿Qué datos recogemos?</h2>
            <p class="text-slate-700">Cuando usas Alumni Connect EFPISC, podemos recoger:</p>
            <ul class="list-disc space-y-1 pl-5 text-slate-700">
                <li>Datos de identificación: nombres, apellidos y número de documento de identidad (DNI).</li>
                <li>Datos de contacto: correo electrónico y, si tú decides compartirlos, teléfono y ciudad.</li>
                <li>Datos académicos: año de egreso y grado obtenido, verificados contra el padrón de la Escuela.</li>
                <li>Datos de tu trayectoria laboral que registres voluntariamente: situación laboral, empresa, cargo y rubro.</li>
                <li>Tus respuestas a las encuestas de seguimiento a egresados que la Escuela publique.</li>
                <li>Datos técnicos de acceso, como la fecha y hora de tus inicios de sesión, con fines de seguridad.</li>
            </ul>
            <p class="text-slate-700">
                Tu contraseña nunca se guarda en texto legible: se almacena cifrada, de modo que ni el
                personal de la Escuela puede leerla.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">3. ¿Para qué usamos tus datos?</h2>
            <p class="text-slate-700">Usamos tu información únicamente para:</p>
            <ul class="list-disc space-y-1 pl-5 text-slate-700">
                <li>Verificar que puedes registrarte como egresado de la Escuela y crear tu cuenta.</li>
                <li>Mostrarte ofertas laborales publicadas para la comunidad de egresados.</li>
                <li>Elaborar indicadores agregados de inserción laboral, que ayudan a la Escuela a mejorar sus programas.</li>
                <li>Invitarte a participar en encuestas de seguimiento a egresados.</li>
                <li>Comunicarte información relevante sobre la plataforma o sobre tu cuenta.</li>
                <li>Mantener un registro de accesos que permita detectar usos indebidos del sistema.</li>
            </ul>
            <p class="text-slate-700">
                No usamos tus datos con fines publicitarios ni los vendemos a terceros.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">4. ¿Cuánto tiempo conservamos tus datos?</h2>
            <p class="text-slate-700">
                Conservamos tus datos mientras mantengas una cuenta activa en la plataforma. Si solicitas
                la eliminación de tu cuenta, o si permaneces inactivo por un periodo prolongado, tus datos
                se conservarán únicamente por el tiempo adicional que exijan las normas académicas o
                administrativas de la universidad, y luego serán eliminados o anonimizados.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">5. ¿Con quién compartimos tus datos?</h2>
            <p class="text-slate-700">Tus datos personales:</p>
            <ul class="list-disc space-y-1 pl-5 text-slate-700">
                <li>No se comparten con empresas ni personas ajenas a la Escuela sin tu autorización expresa.</li>
                <li>
                    Las empresas que publican ofertas laborales en la plataforma solo pueden ver la
                    información de tu perfil que tú decidas hacer visible.
                </li>
                <li>Solo el personal administrativo autorizado de la Escuela accede a tu información completa, para fines de gestión académica y elaboración de reportes internos.</li>
                <li>Podemos compartir información únicamente si una autoridad competente lo exige conforme a ley.</li>
            </ul>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">6. ¿Cómo protegemos tu información?</h2>
            <p class="text-slate-700">
                Aplicamos medidas técnicas razonables para proteger tus datos, como el cifrado de
                contraseñas y el control de acceso por roles, de modo que cada usuario solo vea la
                información que le corresponde.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">7. Tus derechos sobre tus datos</h2>
            <p class="text-slate-700">
                La Ley N.º 29733 te reconoce los siguientes derechos, conocidos como derechos ARCO:
            </p>
            <ul class="list-disc space-y-1 pl-5 text-slate-700">
                <li><strong>Acceso:</strong> puedes pedir una copia de los datos personales que tenemos sobre ti.</li>
                <li><strong>Rectificación:</strong> puedes pedir que corrijamos datos que estén desactualizados o sean incorrectos.</li>
                <li><strong>Cancelación:</strong> puedes pedir que eliminemos tus datos cuando ya no sean necesarios para las finalidades descritas.</li>
                <li><strong>Oposición:</strong> puedes oponerte a un uso específico de tus datos, por un motivo legítimo.</li>
            </ul>
            <p class="text-slate-700">
                Para ejercer cualquiera de estos derechos, puedes actualizar tu información directamente
                desde tu perfil en la plataforma, o comunicarte con Secretaría Académica de la Escuela de
                Formación Profesional de Ingeniería de Sistemas y Computación de la UNDAC, indicando tu
                nombre completo, tu DNI y el derecho que deseas ejercer. Responderemos tu solicitud dentro
                de los plazos que establece la ley.
            </p>

            <h2 class="mt-8 text-lg font-semibold text-slate-900">8. Cambios a esta política</h2>
            <p class="text-slate-700">
                Si esta política cambia, publicaremos la versión actualizada en esta misma página, con la
                fecha de la última actualización.
            </p>
            <p class="mt-6 text-sm text-slate-500">
                Última actualización: {{ now()->format('d/m/Y') }}.
            </p>
